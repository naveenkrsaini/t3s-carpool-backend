CREATE TABLE IF NOT EXISTS public.rides (
  id uuid NOT NULL DEFAULT public.uuid_generate_v7(),
  driver_id uuid NOT NULL,
  origin character varying(255) NOT NULL,
  destination character varying(255) NOT NULL,
  departure_time timestamp with time zone NOT NULL,
  seats_available integer NOT NULL,
  price_per_seat numeric(10, 2) NOT NULL,
  base_fuel_fare numeric(10, 2) NULL DEFAULT 0.00,
  toll_charges numeric(10, 2) NULL DEFAULT 0.00,
  max_price_ceiling numeric(10, 2) NULL,
  status public.ride_status_enum NULL DEFAULT 'scheduled'::public.ride_status_enum,
  luggage_size public.luggage_size_enum NULL DEFAULT 'small'::public.luggage_size_enum,
  is_ac_available boolean NULL DEFAULT true,
  is_smoking_allowed boolean NULL DEFAULT false,
  is_pet_friendly boolean NULL DEFAULT false,
  gender_preference public.gender_preference_enum NULL DEFAULT 'any'::public.gender_preference_enum,
  category_restriction character varying(50) NULL,
  started_at timestamp with time zone NULL,
  completed_at timestamp with time zone NULL,
  created_at timestamp with time zone NULL DEFAULT CURRENT_TIMESTAMP,
  origin_lat numeric(10, 7) NULL DEFAULT 0.0,
  origin_lng numeric(10, 7) NULL DEFAULT 0.0,
  destination_lat numeric(10, 7) NULL DEFAULT 0.0,
  destination_lng numeric(10, 7) NULL DEFAULT 0.0,
  vehicle_number character varying(20) NULL DEFAULT 'PENDING'::character varying,
  vehicle_model character varying(100) NULL DEFAULT 'PENDING'::character varying,